const BY_LOCALE: Record<HandoffLocale, HandoffLabels> = { en, es, fr, de, pt, it, zh, ja }

export function isHandoffLocale(value: unknown): value is HandoffLocale {
  return typeof value === 'string' && (HANDOFF_LOCALES as readonly string[]).includes(value)
}

/** `es-ES` -> `es`; anything unknown falls back to English. */
export function resolveHandoffLocale(value: unknown): HandoffLocale {
  if (typeof value !== 'string') return 'en'
  const base = value.toLowerCase().split(/[-_]/)[0]
  return isHandoffLocale(base) ? base : 'en'
}

export function handoffLabels(locale: HandoffLocale): HandoffLabels {
  return BY_LOCALE[locale]
}
