import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const roots = ['server', 'client/src', 'cli', 'local-runner/src', 'mcp-bridge/src', 'src-tauri/src', 'scripts']
const files = []
function walk(dir) {
  for (const entry of fs.readdirSync(path.join(root, dir), { withFileTypes: true })) {
    const file = `${dir}/${entry.name}`
    if (entry.isDirectory() && !['node_modules', 'dist', 'target', '__tests__', '__fixtures__', 'fixtures'].includes(entry.name)) walk(file)
    else if (entry.isFile() && /\.(ts|tsx|rs|mjs|ps1|sh)$/.test(file) && !/\.(test|spec)\./.test(file) && !file.endsWith('.d.ts')) files.push(file)
  }
}
roots.forEach(walk)
const groups = new Map()
for (const file of files.sort()) {
  let group = path.posix.dirname(file)
  if (group === 'server') {
    const family = path.posix.basename(file).split('-')[0]
    group = ['agent', 'blueprint', 'browser', 'chat', 'code', 'desktop', 'file', 'loop', 'project', 'queue', 'rail', 'ticket', 'telemetry'].includes(family)
      ? `server / ${family}` : 'server / other'
  }
  const entries = groups.get(group) ?? []
  const ext = path.posix.extname(file)
  const stem = path.posix.basename(file, ext)
  const dir = path.posix.dirname(file)
  const candidates = [`${dir}/${stem}.test${ext}`, `${dir}/__tests__/${stem}.test${ext}`]
  const tests = candidates.filter(test => fs.existsSync(path.join(root, test)))
  entries.push(`- [${path.posix.basename(file)}](../../${file})${tests.map(test => ` · [test](../../${test})`).join('')}`)
  groups.set(group, entries)
}
const header = `# Source reference map

Generated by \`npm run docs:source-map\`. This is a navigation index, not an
architectural dependency declaration. Search a heading or filename and read only
the relevant source and tests. Feature prefixes group the legacy server files;
new bounded modules live under \`server/modules/\`.

Includes ${files.length} source/build files. Nearby tests are linked where names
match; integration suites may live elsewhere. Use \`rg\` to find other consumers.

`
const output = header + [...groups].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0).map(([group, entries]) => `## ${group}

${entries.join('\n')}
`).join('\n')
const destination = path.join(root, 'docs/internals/source-map.md')
if (process.argv.includes('--check')) {
  if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== output) {
    console.error('Source map is stale. Run npm run docs:source-map.')
    process.exitCode = 1
  }
} else {
  fs.writeFileSync(destination, output)
  console.log(`Indexed ${files.length} files in docs/internals/source-map.md`)
}
