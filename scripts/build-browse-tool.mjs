// Bundles the run browser tool (server/modules/browser/tool/main.ts and its
// pure policy) into ONE dependency-free CommonJS script and embeds it as a
// string in a generated TypeScript module. The server writes that string under
// ~/.specrails/browser-tool/ at startup and exports its launcher to runs as
// $SPECRAILS_BROWSE, so the tool ships identically in development, the npm
// package and the packaged sidecar. Playwright stays external: the launcher
// points the script at the app's own copy.
//
//   node scripts/build-browse-tool.mjs          regenerate
//   node scripts/build-browse-tool.mjs --check  fail when the generated file is stale
import { build } from 'esbuild'
import { createHash } from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const entry = path.join(root, 'server', 'modules', 'browser', 'tool', 'main.ts')
const target = path.join(root, 'server', 'modules', 'browser', 'tool', 'browse-tool-bundle.generated.ts')

export async function renderBrowseToolModule() {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node18',
    external: ['playwright', 'playwright-core'],
    write: false,
    legalComments: 'none',
    charset: 'utf8',
    logLevel: 'silent',
  })
  const source = `// Specrails run browser tool (generated; do not edit).\n${result.outputFiles[0].text}`
  const version = createHash('sha256').update(source).digest('hex').slice(0, 12)
  return [
    '// GENERATED by scripts/build-browse-tool.mjs from server/modules/browser/tool/main.ts.',
    '// Do not edit. Regenerate with `npm run build:browse-tool`.',
    '/* eslint-disable */',
    `export const BROWSE_TOOL_VERSION = ${JSON.stringify(version)}`,
    `export const BROWSE_TOOL_SOURCE = ${JSON.stringify(source)}`,
    '',
  ].join('\n')
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const output = await renderBrowseToolModule()
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : ''
    if (current !== output) {
      console.error('[build-browse-tool] browse-tool-bundle.generated.ts is stale. Run `npm run build:browse-tool`.')
      process.exitCode = 1
    }
  } else {
    fs.writeFileSync(target, output)
    console.log(`[build-browse-tool] wrote ${path.relative(root, target)}`)
  }
}
